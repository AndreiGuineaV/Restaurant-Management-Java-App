package entititati;

/**
 * Enumerare pentru categoriile de produse disponibile in meniu.
 */
public enum CategorieProdus {
    /**
     * Preparate servite ca aperitiv.
     */
    APERITIV,

    /**
     * Preparate de baza (fel principal).
     */
    FEL_PRINCIPAL,

    /**
     * Deserturi si dulciuri.
     */
    DESERT,

    /**
     * Bauturi calde, reci sau alcoolice.
     */
    BAUTURA
}
